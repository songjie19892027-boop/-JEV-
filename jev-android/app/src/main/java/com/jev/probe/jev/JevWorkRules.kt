package com.jev.probe.jev

/**
 * 职场话术关键词规则层。
 *
 * 为什么要有这一层
 * --------------
 * 上层模型（Qwen3-0.6B）对中文职场黑话几乎是陌生领域，判断力有限。而职场黑话
 * 恰恰是**高度固定的短语**：同一句话在不同公司、不同行业里长得几乎一样。
 * 用词表匹配这类短语，命中就基本可以当真 —— 置信度反而高于那个 0.6B 模型。
 *
 * 它的三个好处：
 *   1. 置信度高且**可解释**（会把命中的原词摊给用户看，而不是给个数字）；
 *   2. 你随时可以自己增删词条，改这个文件就行，不需要重训模型；
 *   3. 与模型结论**互相印证** —— 模型说是派活、词表也命中派活，那基本没跑。
 *
 * 收录原则：宁缺毋滥。像「辛苦你」「尽快」这类在职场里太常见、中性场合也用得很多的
 * 说法**故意不收**（收了会让几乎每条消息都报"疑似派活"，反而没法看）。只收那些
 * 出现就意味着有问题的短语。需要更宽或更严，直接改下面的表。
 *
 * 注意：本层只扫**对方发的**消息（调用方负责筛选），不扫我自己发的内容。
 */
object JevWorkRules {

    enum class Kind(val label: String) {
        /** 把本不属于你的活交给你 */
        ASSIGN("疑似派活"),

        /** 把责任或过错往你身上引 */
        BLAME("疑似推责"),

        /** 不加期限地施压 / 催办 */
        PRESSURE("暗中施压"),

        /** 反向信号：只是通知，不需要你动 */
        NOTIFY("像是纯知会")
    }

    data class Hit(val kind: Kind, val phrase: String)

    private class Rule(val kind: Kind, val phrase: String)

    /**
     * 扫描一条消息，返回命中的词条。
     *
     * 去重规则：**短语之间存在包含关系时只保留长的那条**。
     * 例：文本「出了问题你负责」同时命中推责词条「出了问题你负责」和派活词条
     * 「你负责」——后者是前者的子串，语境已被长词条覆盖。两条都留会让人以为
     * 同一句话"既在派活又在推责"，反而看不出重点。
     *
     * 同一个短语命中多个类别（如「你看着办」既像派活也像施压）**不做去重**，
     * 这是有意保留的：两类都显示，让用户自己判断，比强行归一类安全。
     */
    fun scan(text: String): List<Hit> {
        if (text.isBlank()) return emptyList()
        val raw = RULES.filter { text.contains(it.phrase) }.map { Hit(it.kind, it.phrase) }
        return raw.filter { h ->
            raw.none { o -> o.phrase != h.phrase && o.phrase.contains(h.phrase) }
        }
    }

    /** 按类别归拢，便于 UI 分组展示。 */
    fun byKind(hits: List<Hit>): Map<Kind, List<String>> =
        hits.groupBy { it.kind }.mapValues { e -> e.value.map { it.phrase }.distinct() }

    private fun assign(vararg p: String) = p.map { Rule(Kind.ASSIGN, it) }
    private fun blame(vararg p: String) = p.map { Rule(Kind.BLAME, it) }
    private fun pressure(vararg p: String) = p.map { Rule(Kind.PRESSURE, it) }
    private fun notify(vararg p: String) = p.map { Rule(Kind.NOTIFY, it) }

    private val RULES: List<Rule> =
        // 「你跟一下」这类是派活的典型句式：动词是"跟进/盯"，却不说清是谁的活、给什么资源。
        assign(
            "你看着办", "你跟一下", "你跟进", "跟进一下", "你盯一下", "盯一下",
            "你来牵头", "你牵头", "你来统筹", "你来负责", "你负责",
            "你比较熟", "你熟", "这块你",
            "顺便把", "顺带把", "顺便帮", "顺手把", "顺手帮", "顺手弄",
            "先弄起来", "你先弄", "你来弄", "你弄一下",
            "交给你了", "你来安排", "你这边安排", "你安排一下",
            "你处理一下", "你出面", "你协调一下"
        ) +
            // 推责话术的共同点：把因果反过来讲，让"没告知/没提醒/没跟上"变成你的问题。
            blame(
                "我之前不是说过了", "我不是说过", "我说过了", "我早就说过",
                "当时是你", "是你跟的", "你当时跟的",
                "我以为你知道", "我以为你清楚",
                "你为什么不早说", "你怎么不早说", "早点怎么不说",
                "你确认过的", "你当时确认", "你答应过",
                "你也有责任", "你也有份", "你跑不了",
                "这不是我的事", "不归我管", "跟我没关系",
                "你自己看", "你没提醒我", "你那边没跟上",
                "出了问题你负责", "出问题你负责", "你来担"
            ) +
            // 施压话术：要结果不要过程、不给期限地催、把困难推回给你自己消化。
            pressure(
                "我只要结果", "我不管过程", "看结果",
                "你自己把握", "自己想办法", "想想办法", "克服一下",
                "今天之内", "这两天", "别拖", "抓紧", "我等着",
                "要有说法", "给我个说法", "你觉得呢"
            ) +
            // 反向信号：明确不需要你行动。用于压住"看什么都有深意"的误报。
            notify(
                "同步你一下", "同步一下", "知会你", "告知你", "告知一下",
                "不用回复", "不用管", "供参考", "留个底", "留个记录",
                "跟你说一下", "报备", "我这边已经", "已经处理好了"
            )
}
